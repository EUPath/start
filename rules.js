const AREA = { "생명·의약": ["신경과학", "생명과학"], "심리·인지": ["신경과학", "인지과학·심리"], "공학·컴퓨터": ["공학·AI"], "물리·화학·수학": ["공학·AI"] };
function sameArea(m, f) { return f === "아직 넓게 보고 있어요" || (AREA[m] || []).includes(f); }
function list(v) { return Array.isArray(v) ? v : []; }

function startOf(a) {
  const labLow = a.lab === "아직 없어요" || a.lab === "수업 프로젝트 정도";
  const noMaster = ["학부 3~4학년", "학부 졸업, 일하는 중"].includes(a.stage) || a.phdBase === "석사가 없어요";
  let n;
  if (a.stage === "학부 1~2학년") n = 0;
  else if (a.stage === "학부 3~4학년" && labLow) n = 0;
  else if (noMaster || a.goal === "석사") n = 1;
  else if (a.field === "아직 넓게 보고 있어요" || a.phdBase === "거의 달라요" || a.goal === "아직 모르겠어요" || labLow) n = 3;
  else n = 2;
  const next = n === 0 ? (noMaster || a.stage === "학부 1~2학년" ? 1 : 2) : n === 1 ? 2 : n === 2 ? 3 : 2;
  const nextText = n === 0 ? `준비가 되면 시작점 ${next} ${START[next].name}로 이어집니다.`
    : n === 1 ? "석사 중 연구실 경험이 박사 연락(시작점 2)으로 이어집니다."
    : n === 2 ? "공고 지원(시작점 3)을 같이 보세요. 한쪽 답만 기다리지 않는 편이 낫습니다."
    : "공고를 보다 마음에 드는 연구실이 생기면 직접 연락합니다(시작점 2).";
  return { n, next, nextText, labLow, phd: n >= 2 };
}

// 답에서 읽은 것: 응답을 그대로 되비춘다
// 선택지 값만 쓴다. 자유 입력(전공 이름, 고민)은 남의 주소로 보내는 메일에 실릴 수 있어 넣지 않는다
function readOf(a) {
  const major = a.major === "기타" ? "다른" : a.major;
  const wide = a.field === "아직 넓게 보고 있어요";
  const parts = [a.stage];
  if (major && a.field) parts.push(wide ? `${major} 전공, 분야는 넓게 보는 중` : sameArea(a.major, a.field) ? `${major} 전공, ${a.field}` : `${major} 전공에서 ${a.field} 쪽으로`);
  parts.push({ "석사": "석사 목표", "박사": "박사 목표", "둘 다 생각 중": "석사와 박사 모두 고려", "아직 모르겠어요": "석사·박사 미정" }[a.goal]);
  if (a.lab) parts.push(`연구 경험: ${a.lab}`);
  const c = list(a.country).filter(x => x !== "아직 모르겠어요");
  parts.push(c.length ? c.slice(0, 4).join("·") + (c.length > 4 ? " 등" : "") : "나라 미정");
  if (a.when) parts.push(a.when === "아직 정하지 않았어요" ? "출발 시기 미정" : `${a.when} 출발`);
  parts.push({ "스스로 감당할 수 있어요": "비용은 스스로", "일부는 지원이 필요해요": "비용 일부 지원 필요", "장학금이나 월급이 꼭 있어야 해요": "장학금·월급 필수" }[a.money]);
  return parts.filter(Boolean).join(" · ");
}

// 출발 시기: 같은 시작점이라도 지금 할 일이 달라진다
