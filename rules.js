// 함께 볼 것 하나
function extraOf(a, r) {
  const c = list(a.country);
  if (a.major && a.field && !sameArea(a.major, a.field))
    return ["전공을 잇는 다리를 찾으세요", "지금 전공과 가려는 분야를 잇는 경험 하나를 지원서에 한 문장으로 쓸 수 있어야 합니다."];
  if ((r.n === 1 || r.n === 3) && r.labLow)
    return ["연구 경험을 먼저 채우세요", "인턴이나 연구 보조로 연구실 경험을 만들어 두면 다음 단계가 쉬워집니다."];
  if (String(a.money || "").includes("꼭"))
    return ["월급 나오는 박사, 학비 낮은 나라부터", "유럽 박사는 고용계약인 경우가 많고, 석사는 학비가 낮은 나라부터 보는 편이 맞습니다."];
  if (c.some(x => ["영국", "미국", "호주"].includes(x)))
    return ["유럽과 비교할 기준부터 세우세요", "비자, 시험, 학비, 기간이 나라마다 다릅니다. 내게 중요한 기준 두 가지로 비교하세요."];
  if (c.includes("아직 모르겠어요") || c.length >= 4)
    return ["나라를 둘로 좁히세요", "나라마다 입학, 시험, 학비 규칙이 다릅니다. 두 나라만 깊게 보는 편이 낫습니다."];
  return null;
}

