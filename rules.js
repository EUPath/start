// 마지막 안내: "도움 방식" 답에 맞춰 하나로 잇는다 [제목, 문장, 링크]
// 심층분석과 1대1은 아직 없다: 답장 수로 수요를 잰다 (시장조사). 링크는 결과 메일에만 (화면에는 안 둠)
// 가이드북 판매 전에는 어느 답이든 "준비 중"을 같이 알린다. 알림 약속은 소식 받기(선택 동의)에 체크한 사람에게만, 나머지는 답장으로 청하게 한다
function ctaOf(a) {
  const help = String(a.help || "");
  const notify = a.consentMarketing ? " 나오는 날 적어 주신 메일로 알려 드립니다." : " 나오면 알림을 받고 싶다면 결과 메일에 \"알림\"이라고 답장만 주세요.";
  const soon = LINKS.guide ? "" : " 위에 적은 장들이 담긴 가이드북은 지금 준비 중입니다." + notify;
  if (help.includes("글로")) return ["내 이력에 맞춘 답이 필요하다면", "어떤 프로그램, 어떤 연구실이 맞는지는 이력서를 놓고 봐야 알 수 있습니다. 이력서를 보고 서면으로 길을 짚어 드리는 심층분석을 준비하고 있습니다. 받아 보고 싶다면 결과 메일에 \"심층분석\"이라고 답장만 주세요. 열리면 먼저 알려 드립니다." + soon, LINKS.guide];
  if (help.includes("대화")) return ["직접 묻고 싶다면", "내 상황을 놓고 바로 묻고 답하는 1대1 미팅은 아직 열지 않았습니다. 원한다면 결과 메일에 \"미팅\"이라고 답장만 주세요. 열리면 먼저 알려 드립니다." + soon, LINKS.guide];
  if (LINKS.guide) return ["더 깊이 보려면", "위에 적은 장들은 모두 가이드북에 있습니다. 시작점마다 자세한 길과 워크시트도 같이 있습니다.", LINKS.guide];
  return ["가이드북이 곧 나옵니다", "위에 적은 장들은 모두 가이드북에 담깁니다. 시작점마다 자세한 길과 워크시트도 같이 있습니다." + notify, ""];
}

// 답 전체: 화면과 메일이 같은 것을 그린다
function answerOf(a) {
  const r = startOf(a), x = extraOf(a, r), w = whenOf(a, r);
  const items = [["첫 행동", START[r.n].act], ["그다음", r.nextText]];
  if (w) items.push(w);
  if (x) items.push(["함께 볼 것: " + x[0], x[1]]);
  return { r, read: readOf(a), items, worries: worryOf(a, r), cta: ctaOf(a) };
}
