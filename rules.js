  if (w === "2년 뒤") return ["2년 뒤 출발이라면", "지금은 지원보다 이력을 만드는 시기입니다. 어느 길로 가든 연구 경험이 가장 오래 남습니다."];
  if (r.n === 0) return [`${w} 출발이라면`, "출발보다 남은 학기에 연구 경험 하나를 만드는 게 먼저입니다. 그 경험이 서류의 중심이 됩니다."];
